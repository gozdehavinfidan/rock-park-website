// One-shot: generate M3 color roles for site/css/tokens.css (node tools/make_tokens.mjs)
import { argbFromHex, hexFromArgb, Hct, SchemeTonalSpot, MaterialDynamicColors as M, TonalPalette } from "@material/material-color-utilities";

const seed = Hct.fromInt(argbFromHex("#6b4b8f")); // amethyst
const roles = ["surface", "surfaceDim", "surfaceBright", "surfaceContainerLowest", "surfaceContainerLow", "surfaceContainer",
  "surfaceContainerHigh", "surfaceContainerHighest", "onSurface", "onSurfaceVariant", "outline", "outlineVariant",
  "primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "secondary", "secondaryContainer", "onSecondaryContainer",
  "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer", "error", "inverseSurface", "inverseOnSurface", "scrim"];
const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());

function scheme(isDark) {
  const s = new SchemeTonalSpot(seed, isDark, 0);
  // terracotta tertiary + warm sand neutrals for the brand
  s.tertiaryPalette = TonalPalette.fromInt(argbFromHex("#b4532a"));
  if (!isDark) { s.neutralPalette = TonalPalette.fromHueAndChroma(70, 10); s.neutralVariantPalette = TonalPalette.fromHueAndChroma(60, 14); }
  else { s.neutralPalette = TonalPalette.fromHueAndChroma(300, 5); s.neutralVariantPalette = TonalPalette.fromHueAndChroma(300, 8); }
  return roles.map((r) => `  --md-sys-color-${kebab(r)}: ${hexFromArgb(M[r].getArgb(s))};`).join("\n");
}
console.log(`/* Generated by tools/make_tokens.mjs — M3 roles, seed #6b4b8f, tertiary #b4532a */\n:root, .theme-night {\n${scheme(true)}\n}\n.theme-sand {\n${scheme(false)}\n}`);
